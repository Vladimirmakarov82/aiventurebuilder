SOFT = [
    (r' — ', 'тире-пауза: лучше точка или двоеточие'),
    (r'уникальн|инновацион|эффективн|оптимальн|индивидуальн(ый|ого) подход|широкий спектр', 'оценка без цифры'),
    (r'\bпремиальн|\bэксклюзивн|\bлакшери|\bлюкс', 'слово-ярлык вместо примера'),
]

def visible_text(path):
    s = open(path, encoding='utf-8').read()
    s = re.sub(r'<script.*?</script>|<style.*?</style>|<svg.*?</svg>', ' ', s, flags=re.S)
    s = re.sub(r'<head>.*?</head>', ' ', s, flags=re.S)
    s = re.sub(r'<[^>]+>', '\n', s)
    s = html.unescape(s).replace('\xa0', ' ')
    return [l.strip() for l in s.split('\n') if l.strip()]

def lint_lines(lines):
    hard, soft = [], []
    for l in lines:
        low = l.lower()
        for rx, why in HARD:
            if re.search(rx, low): hard.append((why, l))
        for rx, why in SOFT:
            if re.search(rx, low): soft.append((why, l))
    return hard, soft

if __name__ == '__main__':
    lines = visible_text(sys.argv[1])
    # also lint JS-injected RU data passed as extra files of plain text lines
    for extra in sys.argv[2:]:
        lines += [l.strip() for l in open(extra, encoding='utf-8') if l.strip()]
    hard, soft = lint_lines(lines)
    # POOL rule: hero animation items are bare names of rare things, max 4 words, no descriptors
    import json, os
    for page in [sys.argv[1], os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(sys.argv[1]))), 'index.html')]:
        if not os.path.exists(page): continue
        m = re.search(r'window\.__POOL=(\[.*?\]);', open(page, encoding='utf-8').read(), re.S)
        if not m: continue
        for it in json.loads(m.group(1)):
            if re.fullmatch(r'[A-Za-z][\w.-]* pre-IPO \+\d+%', it): continue  # pre-IPO deal: «Name +N%» (owner data, IPO Sharks)
            if len(it.split()) > 4: hard.append(('POOL: больше 4 слов, нужно только имя', it))
            if re.search(r'с бриллиант|для семьи|через spv|до ipo|в полном|без масла|в платине|без объявлений|with diamonds|for the family|via spv|before the ipo|full set|in platinum', it.lower()):
                hard.append(('POOL: пояснение вместо имени', it))
            if re.search(r'\d+\s*(лет|years)|одн(а|и|о) из|one of', it.lower()):
                hard.append(('POOL: тираж или срок вместо имени', it))
    for why, l in hard: print('ERROR', why, '|', l[:140])
    for why, l in soft: print('warn ', why, '|', l[:140])
    print(f'{len(hard)} errors, {len(soft)} warnings')
    sys.exit(1 if hard else 0)
